#!/usr/bin/env bash
# Run an EmberWatch ML module on Kaggle, from the exact current git commit.
#
# The Kaggle job clones this repo at HEAD, installs ml/pyproject.toml, writes
# env.json (GPU + library versions), runs the module, and saves its outputs.
# Jobs run on Kaggle's servers, so they keep going if this laptop sleeps;
# `fetch` downloads results afterwards.
#
# Usage:
#   scripts/kaggle_run.sh run    <slug> "<module> [args]" [options]
#   scripts/kaggle_run.sh status <slug>
#   scripts/kaggle_run.sh wait   <slug>                  # poll until finished, then fetch
#   scripts/kaggle_run.sh fetch  <slug> [--fetch REGEX]
#
# Options for `run`:
#   --gpu             request a T4 x2 GPU (uses weekly GPU quota)
#   --extras LIST     comma-separated pyproject extras to install (e.g. train)
#   --source SLUG     attach another kernel's output as input (repeatable)
#   --fetch REGEX     which output files to download (default: small files only)
#   --no-wait         push and return immediately
#
# Example:
#   scripts/kaggle_run.sh run emberwatch-data "src.data.pyro_sdis"
set -euo pipefail

KAGGLE_USER="alihassancoder"
REPO_URL="https://github.com/alihassan-coder/emberwatch.git"
ROOT="$(git rev-parse --show-toplevel)"
# Kaggle CLI 2.2.5 imports `six` without declaring it.
KAGGLE=(uvx --python 3.12 --with six kaggle@latest)
DEFAULT_FETCH='\.(json|md|log|csv|txt|png)$'
POLL_SECONDS=180  # Kaggle rate-limits frequent polling

die() { echo "error: $*" >&2; exit 1; }
log() { printf '\033[1;34m[kaggle]\033[0m %s\n' "$*"; }

run_dir()   { echo "$ROOT/ml/artifacts/runs/$1"; }

kstatus() {
  "${KAGGLE[@]}" kernels status "$KAGGLE_USER/$1" 2>&1 | tail -1
}

fetch() {
  local slug="$1" pattern="${2:-$DEFAULT_FETCH}" dest
  dest="$(run_dir "$slug")"
  mkdir -p "$dest"
  log "downloading outputs matching /$pattern/ -> ${dest#"$ROOT"/}"
  "${KAGGLE[@]}" kernels output "$KAGGLE_USER/$slug" -p "$dest" -o -q --file-pattern "$pattern" || true
  local n size
  n=$(find "$dest" -type f | wc -l); size=$(du -sh "$dest" | cut -f1)
  log "fetched $n file(s), $size total"
  local logfile
  logfile=$(find "$dest" -maxdepth 1 -name '*.log' | head -1)
  if [[ -n "$logfile" ]]; then
    log "last lines of the Kaggle log:"
    # Kaggle logs are JSON lines: [{"stream_name":..,"data":..}, ...]
    python3 - "$logfile" <<'PY' || tail -n 30 "$logfile"
import json, sys
raw = open(sys.argv[1]).read()
try:
    entries = json.loads(raw)
    text = "".join(e.get("data", "") for e in entries)
except Exception:
    text = raw
print("\n".join(text.rstrip().splitlines()[-30:]))
PY
  fi
}

wait_for() {
  local slug="$1" pattern="${2:-$DEFAULT_FETCH}" start status
  start=$(date +%s)
  while true; do
    status="$(kstatus "$slug")"
    log "$(date +%H:%M:%S) +$(( ($(date +%s) - start) / 60 ))m  $status"
    case "${status,,}" in
      *complete*) fetch "$slug" "$pattern"; return 0 ;;
      *error*|*cancel*) fetch "$slug" "$pattern"; die "run $slug failed (see log above)" ;;
    esac
    sleep "$POLL_SECONDS"
  done
}

cmd_run() {
  local slug="$1" module="$2"; shift 2
  local gpu=0 extras="" fetch_pattern="$DEFAULT_FETCH" wait=1 sources=()
  while (( $# )); do
    case "$1" in
      --gpu) gpu=1 ;;
      --extras) extras="$2"; shift ;;
      --source) sources+=("\"$KAGGLE_USER/$2\""); shift ;;
      --fetch) fetch_pattern="$2"; shift ;;
      --no-wait) wait=0 ;;
      *) die "unknown option $1" ;;
    esac
    shift
  done

  # The job runs the committed code, so uncommitted ML changes would be ignored.
  git -C "$ROOT" diff --quiet HEAD -- ml scripts ':!ml/uv.lock' || die "commit your ml/ changes first (the Kaggle job runs HEAD)"
  local sha branch
  sha="$(git -C "$ROOT" rev-parse HEAD)"
  branch="$(git -C "$ROOT" branch --show-current)"
  log "pushing $branch@${sha:0:7} to GitHub so Kaggle can clone it"
  git -C "$ROOT" push -q origin "HEAD:refs/heads/$branch"

  local push_dir
  push_dir="$(run_dir "$slug")/push"
  rm -rf "$push_dir"; mkdir -p "$push_dir"

  cat > "$push_dir/run.py" <<PY
# Generated by scripts/kaggle_run.sh. Do not edit on Kaggle.
import os, subprocess, time

REPO = "$REPO_URL"
SHA = "$sha"
MODULE = "$module"
EXTRAS = "$extras"

def sh(cmd, **kw):
    print(f"\n\$ {cmd}", flush=True)
    t = time.time()
    subprocess.run(cmd, shell=True, check=True, **kw)
    print(f"  ({time.time() - t:.0f}s)", flush=True)

import socket
try:
    socket.getaddrinfo("github.com", 443)
except OSError:
    raise SystemExit(
        "EMBERWATCH: this Kaggle session has NO INTERNET. Kaggle blocks internet (and GPUs) "
        "until the account's phone number is verified: https://www.kaggle.com/settings"
    )

sh(f"git clone --quiet --filter=blob:none {REPO} /tmp/emberwatch && git -C /tmp/emberwatch checkout --quiet {SHA}")
sh("pip install --quiet uv")
extra_flags = " ".join(f"--extra {e}" for e in EXTRAS.split(",") if e)
sh(f"cd /tmp/emberwatch/ml && uv pip install --system --break-system-packages --quiet -r pyproject.toml {extra_flags}")
env = dict(os.environ, EMBERWATCH_GIT_SHA=SHA, PYTHONUNBUFFERED="1")
sh("cd /tmp/emberwatch/ml && python -m src.common.env_report", env=env)
sh(f"cd /tmp/emberwatch/ml && python -m {MODULE}", env=env)
PY

  local src_json
  src_json="$(IFS=,; echo "${sources[*]:-}")"
  cat > "$push_dir/kernel-metadata.json" <<JSON
{
  "id": "$KAGGLE_USER/$slug",
  "title": "$slug",
  "code_file": "run.py",
  "language": "python",
  "kernel_type": "script",
  "is_private": true,
  "enable_gpu": $([[ $gpu == 1 ]] && echo true || echo false),
  "enable_tpu": false,
  "enable_internet": true,
  "dataset_sources": [],
  "competition_sources": [],
  "kernel_sources": [$src_json],
  "model_sources": []
}
JSON

  local accel=()
  [[ $gpu == 1 ]] && accel=(--accelerator NvidiaTeslaT4)
  log "starting Kaggle job $KAGGLE_USER/$slug  (module: $module, gpu: $gpu, extras: ${extras:-none})"
  "${KAGGLE[@]}" kernels push -p "$push_dir" "${accel[@]}"
  log "view it live: https://www.kaggle.com/code/$KAGGLE_USER/$slug"

  (( wait )) && wait_for "$slug" "$fetch_pattern"
  return 0
}

case "${1:-}" in
  run)    shift; [[ $# -ge 2 ]] || die "usage: run <slug> \"<module> [args]\" [options]"; cmd_run "$@" ;;
  status) kstatus "${2:?slug}" ;;
  wait)   wait_for "${2:?slug}" "${4:-$DEFAULT_FETCH}" ;;
  fetch)  fetch "${2:?slug}" "${4:-$DEFAULT_FETCH}" ;;
  *) sed -n '2,25p' "$0"; exit 1 ;;
esac
